// Temporary account/database; no external AI requests or production writes.
import assert from 'node:assert/strict';
import {mkdir,mkdtemp,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {startServer} from '../server.mjs';
import {addDays} from '../public/schedule.js';
const root=process.cwd();await mkdir('.qa',{recursive:true});
const {chromium}=await import(pathToFileURL(resolve(process.env.QA_PLAYWRIGHT||'.qa/browser-tools/node_modules/playwright/index.mjs')));
const server=await startServer({host:'127.0.0.1',port:0,dataDir:await mkdtemp(join(root,'.qa','nutrition-feedback-'))});
const base=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({executablePath:process.env.QA_BROWSER||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
try {
 const context=await browser.newContext({viewport:{width:1366,height:1000},timezoneId:'Asia/Shanghai'});
 const page=await context.newPage(),errors=[],snapshots=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('response',async response=>{if(response.url().endsWith('/api/compute')){try{const data=await response.json();if(data.result?.nutritionFeedback)snapshots.push(data.result);}catch{}}});
 const date=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Shanghai',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
 const start=addDays(date,-14),profile={age:30,sex:'male',height:175,weight:70,goal:'maintain',activity:1.375};
 const registered=await context.request.post(base+'/api/auth/register',{data:{name:'热量校准验证',email:`feedback-${Date.now()}@example.test`,password:'qa-password-123'}});
 assert.equal(registered.status(),201);const {user}=await registered.json();
 const sync=await context.request.post(base+'/api/sync',{data:{userId:user.id,changes:[{id:'profile',kind:'profile',data:profile,baseVersion:0},{id:'phase:start',kind:'phase',data:{...profile,date:start},baseVersion:0}]}});
 assert.equal(sync.status(),200);
 await page.goto(base);await page.locator('.nav [data-page="nutrition"]').click();
 await page.locator('#nutrition-feedback [data-feedback-offset]').waitFor();
 assert.equal(await page.locator('[data-feedback-offset]').textContent(),'0');
 assert.match(await page.locator('#nutrition-feedback').innerText(),/可以校准/);
 await page.locator('#nutrition-feedback [data-action="profile"]').click();
 await page.locator('#profile-weight').fill('71');
 await page.locator('#profile-form button[type="submit"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-feedback-offset]')?.textContent==='-100');
 assert.equal(snapshots.at(-1).nutritionFeedback.cycleCount,1);
 assert.equal(snapshots.at(-1).advice[date].balance.kcal.target,snapshots.at(-1).nutrition.rest.kcal);
 await page.locator('#nutrition-feedback summary').click();
 await page.locator('#nutrition-feedback-manual').fill('50');
 await page.locator('#nutrition-feedback-form button[type="submit"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-feedback-offset]')?.textContent==='-50');
 await page.reload();await page.locator('.nav [data-page="nutrition"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-feedback-offset]')?.textContent==='-50');
 assert.equal(snapshots.at(-1).nutritionFeedback.cycleCount,1,'reload does not apply a second cycle');
 await page.screenshot({path:'.qa/nutrition-feedback-desktop.png',fullPage:true});
 await page.locator('#nutrition-feedback summary').click();
 await page.locator('#nutrition-feedback-form input[name="enabled"]').uncheck();
 await page.locator('#nutrition-feedback-form button[type="submit"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-feedback-offset]')?.textContent==='+50');
 await page.locator('#nutrition-date').fill(start);await page.locator('#nutrition-date').dispatchEvent('change');
 await page.waitForFunction(()=>document.querySelector('[data-feedback-offset]')?.textContent==='0');
 assert.equal(await page.locator('#nutrition-feedback-form').count(),0);
 await page.locator('#nutrition-date').fill(date);await page.locator('#nutrition-date').dispatchEvent('change');
 await page.waitForFunction(()=>document.querySelector('[data-feedback-offset]')?.textContent==='+50');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#nutrition-feedback summary').click();
 await page.locator('#nutrition-feedback').scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1),false,'mobile layout has no horizontal overflow');
 await page.screenshot({path:'.qa/nutrition-feedback-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 const evidence={date,cycleCount:snapshots.at(-1).nutritionFeedback.cycleCount,manualCorrection:snapshots.at(-1).nutritionFeedback.manualAdjustmentKcal,finalCorrection:snapshots.at(-1).nutritionFeedback.adjustmentKcal,errors};
 await writeFile('.qa/nutrition-feedback-browser.json',JSON.stringify(evidence,null,2));
 console.log('PASS: weight entry automatically calibrates; editable correction and toggle persist; reload is idempotent; historical targets stay unchanged; mobile has no overflow.',evidence);
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
