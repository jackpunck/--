export const dailyQuotes = Object.freeze(rows.map(([title, ...lines]) =>
  Object.freeze({title, lines:Object.freeze(lines)})));

export function getDailyQuote(date = new Date()) {
  // Convert local calendar components to a day number without DST hour shifts.
  const day = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const offset = Math.round((day - Date.UTC(2026, 9, 2)) / 86400000);
  return dailyQuotes[((offset % dailyQuotes.length) + dailyQuotes.length) % dailyQuotes.length];
}
